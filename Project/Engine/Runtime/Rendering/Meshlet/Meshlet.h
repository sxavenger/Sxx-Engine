namespace Meshlet {

	//-----------------------------------------------------------------------------------------
	// constant variables
	//-----------------------------------------------------------------------------------------

	constexpr const uint32_t kMaxVertices  = 64;
	constexpr const uint32_t kMaxTriangles = 128;

	constexpr const float kConeWeight = 0.5f;

	constexpr const uint32_t kAmplificationThreadCount = 32;

	////////////////////////////////////////////////////////////////////////////////////////////
	// Description structure
	////////////////////////////////////////////////////////////////////////////////////////////
	struct Description { //!< [meshopt_Meshlet参照] メッシュレットの頂点/三角形のオフセットと数
	public:

		//=========================================================================================
		// public variables
		//=========================================================================================

		uint32_t vertexOffset;
		uint32_t triangleOffset;
		uint32_t vertexCount;
		uint32_t triangleCount;

	};

	////////////////////////////////////////////////////////////////////////////////////////////
	// Triangle structure
	////////////////////////////////////////////////////////////////////////////////////////////
	struct Triangle { //!< メッシュレット内の1三角形を構成するローカル頂点index(各10bit)
	public:

		//=========================================================================================
		// public variables
		//=========================================================================================

		uint32_t i0 : 10;
		uint32_t i1 : 10;
		uint32_t i2 : 10;
		//!< 1頂点当たり10bitで表現 計30bit(約uint32_t)

	};

	////////////////////////////////////////////////////////////////////////////////////////////
	// Bounds structure
	////////////////////////////////////////////////////////////////////////////////////////////
	struct Bounds { //!< [meshopt_Bounds参照] メッシュレットのバウンディング情報
	public:

		//=========================================================================================
		// public variables
		//=========================================================================================

		Vector3f center; //!< bounding sphereの中心
		float radius;    //!< bounding sphereの半径

		Vector3<int8_t> coneAxis; //!< normal coneの軸 (SNORM8, x / 127.0fでデコード)
		int8_t coneCutoff;        //!< normal coneのcutoff (SNORM8, x / 127.0fでデコード)
		//!< cone apexは保持しない. bounding sphereを使う判定式で代用する.
		
	};

}

