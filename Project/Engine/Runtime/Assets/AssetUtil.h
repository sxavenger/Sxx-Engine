////////////////////////////////////////////////////////////////////////////////////////////
// AssetType enum class
////////////////////////////////////////////////////////////////////////////////////////////
enum class AssetType : uint8_t {
	Texture,
	Unknown,
};

////////////////////////////////////////////////////////////////////////////////////////////
// MetadataType enum class
////////////////////////////////////////////////////////////////////////////////////////////
enum class MetadataType : uint8_t {
	Unknown,
	Reference,
	Inline
};

////////////////////////////////////////////////////////////////////////////////////////////
// FileType enum class
////////////////////////////////////////////////////////////////////////////////////////////
enum class FileType : bool {
	Asset = true,
	Other = false
};

//=========================================================================================
// constant variables
//=========================================================================================

static inline std::filesystem::path kAssetFileExtension = ".asset";
static inline Uuid kAssetNullUuid = { NULL, NULL, NULL, NULL, NULL };

////////////////////////////////////////////////////////////////////////////////////////////
// methods
////////////////////////////////////////////////////////////////////////////////////////////

inline FileType CheckFileType(const std::filesystem::path& extension) noexcept {
	return (extension == kAssetFileExtension) ? FileType::Asset : FileType::Other; //!< 拡張子が".asset"の場合はAsset, それ以外はOther
}

