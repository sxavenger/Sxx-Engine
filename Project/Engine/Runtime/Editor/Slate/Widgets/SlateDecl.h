namespace Slate {

	////////////////////////////////////////////////////////////////////////////////////////////
	// Decl structure
	////////////////////////////////////////////////////////////////////////////////////////////
	template <class T> requires std::derived_from<T, Widget>
	struct Decl {
	public:

		//=========================================================================================
		// public methods
		//=========================================================================================

		//* constructor *//

		Decl() : pointer(std::make_shared<T>()) {}

		//* operator [access] *//

		T* operator->() const { return pointer.get(); }

		//=========================================================================================
		// public variables
		//=========================================================================================

		std::shared_ptr<T> pointer = nullptr;

	};

}

